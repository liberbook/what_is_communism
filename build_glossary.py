def main() -> None:
    ap = argparse.ArgumentParser()
    here = Path(__file__).resolve().parent
    ap.add_argument("--corpus", type=Path, default=None,
                    help="directory of exported .txt parts (default: read russian/parts/*.tex)")
    ap.add_argument("--lang", choices=sorted(LANGS), default="it", help="target language (default: it)")
    ap.add_argument("--out", type=Path, default=None,
                    help="output file (default: italiano/glossary.ru-it.json or english/glossary.ru-en.json)")
    args = ap.parse_args()
    out = args.out or here / LANGS[args.lang]["out"]

    if args.lang == "en":
        sources = [e[0] for e in ENTRIES]
        missing = [x for x in sources if x not in EN_TARGETS]
        extra = [x for x in EN_TARGETS if x not in sources]
        if missing or extra:
            raise SystemExit(f"EN_TARGETS out of sync with ENTRIES: missing {missing}, extra {extra}")

    if args.corpus:
        corpus = "\n\n".join(p.read_text(encoding="utf-8") for p in sorted(args.corpus.glob("*.txt")))
    else:
        corpus = russian_corpus(here / "russian" / "parts")
    tokens = [(m.group(0), m.start(), m.end()) for m in CYR_TOKEN.finditer(corpus)]

    seen: dict[str, dict] = {}
    unmatched: list[str] = []
    for source, target, category, note in ENTRIES:
        variants = corpus_variants(source, corpus, tokens)
        alts = [source] + [v for v in variants if v != source]
        key = "|".join(alts)
        if not variants and source not in corpus:
            unmatched.append(source)
        if args.lang == "en":
            target, note = EN_TARGETS[source], ""
        entry = {"source": key, "target": target, "category": category}
        if note:
            entry["_note"] = note
        seen[source] = entry

    glossary = {
        "name": LANGS[args.lang]["name"],
        "_about": LANGS[args.lang]["about"],
        "terms": list(seen.values()),
    }
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(glossary, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    total_alts = sum(len(t["source"].split("|")) for t in glossary["terms"])
    print(f"wrote {out}: {len(glossary['terms'])} terms, {total_alts} source forms")
    print(f"{len(unmatched)} sources without a literal occurrence in the corpus:")
    for s in unmatched:
        print(f"  - {s}")


if __name__ == "__main__":
    main()
